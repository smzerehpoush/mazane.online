/**
 * فهرست صفحه‌های موجود — «چه چیزی وجود دارد»، جدا از «قیمتش چند است».
 *
 * تنها قاعده‌ی این ماژول: **payload زنده مقدم است، رجیستری ایستا کف است.**
 *
 *   - ردیس زنده ⟸ همان چیزی که گردآورنده نوشته (شامل هر سکو/دارایی‌ای که
 *     پس از آخرین دیپلوی وب اضافه شده و هر پرچم `published` تازه‌بازشده).
 *   - ردیس قطع (یا فهرست تهی) ⟸ `lib/registry.ts`، یعنی همان فهرستی که در
 *     زمان بیلد از رجیستری کد گردآورنده آینه شده است.
 *
 * چرا کف لازم است: پیش از این، هویت صفحه به ردیسِ زنده گره خورده بود و قطع
 * ردیس ۱۴ صفحه‌ی دارایی و سکو را ۴۰۴ می‌کرد — نقض قاعده‌ی ۵ قراردادها،
 * و ۴۰۴ی که لبه کشش می‌کرد. فهرست سکوها و دارایی‌ها فراداده‌ی ثابت است و
 * فقط با دیپلوی عوض می‌شود؛ گره زدنش به داده‌ی زنده از اول اشتباه بود.
 *
 * چرا «تهی» هم مثل «قطع» حساب می‌شود: منبع ردیس هر خطای اتصال را به فهرست
 * تهی ترجمه می‌کند (قاعده‌ی ۵) — پس این لایه اصلاً نمی‌تواند «قطع» را از
 * «هیچ سکویی ثبت نشده» تشخیص دهد، و رجیستری ایستا برای هر دو، پاسخ درست
 * و صادقانه است.
 *
 * ⚠️ این ماژول هیچ فرمول قیمتی و هیچ عدد بین‌سکویی ندارد (قاعده‌های ۱ و ۴)
 * و هیچ وابستگی نودی ندارد، پس import شدنش از هر دو سو بی‌خطر است.
 */
import {
  getInstruments,
  getListedPlatforms,
  type InstrumentListing,
  type ListedPlatform,
} from "./prices";
import { REGISTRY_INSTRUMENTS, REGISTRY_PLATFORMS } from "./registry";

/** سکوهای قابل نمایش عمومی — زنده اگر باشد، وگرنه رجیستری بیلد. */
export async function listPlatforms(): Promise<ListedPlatform[]> {
  const live = await getListedPlatforms();
  return live.length > 0 ? live : [...REGISTRY_PLATFORMS];
}

/** دارایی‌ها با پرچم دروازه‌ی انتشار — زنده اگر باشد، وگرنه رجیستری بیلد. */
export async function listInstruments(): Promise<InstrumentListing[]> {
  const live = await getInstruments();
  return live.length > 0 ? live : [...REGISTRY_INSTRUMENTS];
}
