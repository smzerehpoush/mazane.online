export function jewelryInterpretation(breakdown: JewelryBreakdown | null): string | null {
  if (breakdown === null || breakdown.extraCostPercent === null) return null;
  const extra = breakdown.wage + breakdown.profit + breakdown.vat;
  if (extra <= 0) return null;
  const share = formatFaPercentPoints(breakdown.extraCostPercent, { maximumFractionDigits: 1 });
  return `از این مبلغ، ${formatFaNumber(extra)} تومان هزینه‌ی افزوده روی ارزش طلاست؛ یعنی ${share} بیشتر از ارزش خود طلا.`;
}
