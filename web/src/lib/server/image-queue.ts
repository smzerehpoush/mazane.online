/**
 * صف تک‌نفره‌ی پردازش عکس (بلیت ۲۴) — یک زنجیره‌ی Promise ساده، بدون
 * وابستگی تازه.
 *
 * سرور تولید یک هسته دارد و با پروژه‌ی پادل‌یار مشترک است (Dockerfile.web).
 * `sharp` پردازنده‌بر است؛ اگر دو آپلود هم‌زمان اجرا شوند، هر دو پردازنده را
 * برای چند ثانیه قفل می‌کنند و رندر صفحه‌ی عمومی کند می‌شود. این صف تضمین
 * می‌کند در هر لحظه حداکثر یک پردازش/آپلود در جریان است — کارها هرکدام
 * منتظر تمام‌شدنِ قبلی می‌مانند، چه قبلی موفق شده باشد چه شکست خورده.
 *
 * **فقط سمت سرور** — تنها مصرف‌کننده‌اش `image-store.ts` است.
 */
import "@tanstack/react-start/server-only";

/** دم صف — همیشه به یک Promise «حل‌شده» می‌رسد، حتی اگر کارِ قبلی رد شده باشد. */
let tail: Promise<void> = Promise.resolve();

/**
 * کار را به صف اضافه می‌کند و بعد از تمام‌شدن نوبتش اجرا می‌کند. نتیجه/خطای
 * خودِ کار به فراخوان برمی‌گردد؛ فقط ترتیب اجرا سریالی می‌شود.
 */
export function enqueueImageJob<T>(job: () => Promise<T>): Promise<T> {
  const started = tail.then(job);
  tail = started.then(
    () => undefined,
    () => undefined,
  );
  return started;
}
